import { plain, zmw } from './money';

export interface ShareReport {
  name: string; title: string; period: string;
  columns: { key: string; header: string; type: 'text' | 'money' | 'int' | 'number' | 'date'; width: number }[];
  rows: Record<string, unknown>[]; totals: Record<string, unknown> | null;
  summary: { label: string; value: number | string; money?: boolean }[];
}
interface Options { report: ShareReport; rows?: Record<string, unknown>[]; generatedBy: string; search?: string }

export async function billingReportPdf({ report, rows = report.rows, generatedBy, search }: Options): Promise<Blob> {
  const [{ jsPDF }, { default: autoTable }] = await Promise.all([import('jspdf'), import('jspdf-autotable')]);
  const doc = new jsPDF({ orientation: 'landscape', unit: 'mm', format: 'a4' });
  const width = doc.internal.pageSize.getWidth(), height = doc.internal.pageSize.getHeight();
  doc.setProperties({ title: report.title, subject: report.period, author: generatedBy, creator: 'SES EHR' });
  doc.setFontSize(16); doc.setTextColor(31, 95, 150); doc.text(`SES EHR · ${report.title}`, 14, 15);
  doc.setFontSize(9); doc.setTextColor(70); doc.text(report.period, 14, 21);
  let y = 27;
  if (search) {
    const note = doc.splitTextToSize(`Filtered by “${search}”: ${rows.length} of ${report.rows.length} rows. Totals cover the full report.`, width - 28);
    doc.text(note, 14, y); y += note.length * 4 + 2;
  }
  const summary = doc.splitTextToSize(report.summary.map(s => `${s.label}: ${typeof s.value === 'number' ? s.money ? zmw(s.value) : s.value.toLocaleString('en-US') : s.value}`).join('   |   '), width - 28);
  doc.text(summary, 14, y); y += summary.length * 4 + 3;
  const cell = (column: ShareReport['columns'][number], value: unknown): string => {
    if (value === null || value === undefined || value === '') return '—';
    if (column.type === 'money') return plain(Number(value));
    if (column.type === 'int' || column.type === 'number') return Number(value).toLocaleString('en-US');
    if (column.type === 'date') return new Date(value as string).toLocaleString('en-GB', { day: '2-digit', month: 'short', year: 'numeric', ...(column.key === 'time' ? { hour: '2-digit', minute: '2-digit' } : {}) });
    return String(value);
  };
  const numeric = (type: string) => ['money', 'int', 'number'].includes(type);
  autoTable(doc, {
    startY: y, margin: { top: 16, right: 14, bottom: 20, left: 14 },
    head: [report.columns.map(column => column.header)],
    body: rows.map(row => report.columns.map(column => cell(column, row[column.key]))),
    foot: report.totals ? [report.columns.map(column => report.totals![column.key] === undefined ? '' : cell(column, report.totals![column.key]))] : undefined,
    showFoot: 'lastPage', theme: 'grid', styles: { fontSize: 8, cellPadding: 1.8, overflow: 'linebreak' },
    headStyles: { fillColor: [31, 95, 150] }, footStyles: { fillColor: [238, 243, 248], textColor: [27, 31, 35] },
    columnStyles: Object.fromEntries(report.columns.map((column, index) => [index, { halign: numeric(column.type) ? 'right' : 'left' }])),
    didParseCell: data => { data.cell.styles.halign = numeric(report.columns[data.column.index].type) ? 'right' : 'left'; },
    didDrawPage: () => {
      doc.setFontSize(8); doc.setTextColor(91, 102, 112);
      doc.text(`Generated by ${generatedBy}`, 14, height - 11, { maxWidth: width - 45 });
      doc.text(`Page ${doc.getCurrentPageInfo().pageNumber}`, width - 14, height - 11, { align: 'right' });
    },
  });
  return doc.output('blob');
}

export async function shareBillingReport(options: Options): Promise<'shared' | 'downloaded' | 'cancelled'> {
  const blob = await billingReportPdf(options);
  const filename = `ses-${options.report.name}.pdf`;
  if (typeof File !== 'undefined' && navigator.share && navigator.canShare) {
    const file = new File([blob], filename, { type: 'application/pdf' });
    try {
      if (navigator.canShare({ files: [file] })) {
        await navigator.share({ files: [file], title: options.report.title });
        return 'shared';
      }
    } catch (error) {
      if ((error as { name?: string })?.name === 'AbortError') return 'cancelled';
      // Devices without file sharing still receive an attachable PDF below.
    }
  }
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url; link.download = filename; document.body.appendChild(link); link.click(); link.remove();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
  return 'downloaded';
}
